"""Retain failed preparation evidence and remove only byte-checked duplicates."""
import hashlib
import io
import json
from pathlib import Path
import shutil
import tarfile
import sys

ROOT = Path(__file__).resolve().parents[4]
SERIES = Path(__file__).resolve().parent
WORK = ROOT/'build/m10-host-clock-v1'
sys.path.insert(0, str(ROOT/'tests/integration/perception'))
from runtime_restoration_v1 import sha
def read(path): return json.loads(path.read_text())
def identity(path): return dict(bytes=path.stat().st_size, sha256=sha(path))
def digest(data): return dict(bytes=len(data), sha256=hashlib.sha256(data).hexdigest())
def write(path, value):
    assert not path.exists()
    path.write_text(json.dumps(value, indent=2)+'\n')
def add(tar, name, data):
    info=tarfile.TarInfo(name); info.size=len(data); info.mode=0o644
    tar.addfile(info, io.BytesIO(data))

# This failure has no images or physical trace rows. Retain every original
# run member in a small review archive; do not invent a physical anchor.
bundle=SERIES/'normal-30s-02'; run=WORK/'normal-30s-02/archive-check/run'
manifest=read(bundle/'run-manifest.json'); target=bundle/'retained-metadata.tar.gz'
assert not target.exists() and not read(bundle/'raw-manifest.json')['archives']
review=dict(schema='m10-retained-review-v1', scope='All original pre-native failure members; zero physical receipts and raw images',
    original_archive=manifest['archive'], original_archive_sha256=manifest['sha256'],
    original_members=manifest['members'], derived={})
with tarfile.open(target,'w:gz') as tar:
    for name, expected in manifest['members'].items():
        data=(run/name).read_bytes(); assert digest(data)==expected; add(tar,name,data)
    add(tar,'MANIFEST.json',(json.dumps(review,indent=2)+'\n').encode())
with tarfile.open(target,'r:gz') as tar:
    assert set(tar.getnames())==set(manifest['members'])|{'MANIFEST.json'}
    for name, expected in manifest['members'].items(): assert digest(tar.extractfile(name).read())==expected
write(bundle/'retained-metadata.json',dict(status='PASS',archive=target.name,**identity(target),
    original_members=len(manifest['members']), derived_window_rows=0, full_run_preserved_locally=True))

compaction=read(WORK/'compaction.log')
assert compaction['status']=='PASS'
write(SERIES/'normal-30s-01/compaction-validation.json',compaction)
removed=[]
for case_name in ('normal-30s-01','normal-30s-02'):
    bundle=SERIES/case_name; run=WORK/case_name/'archive-check/run'
    manifest=read(bundle/'run-manifest.json'); raw=read(bundle/'raw-manifest.json')
    assert read(bundle/'archive-validation.json')['status']=='PASS'
    assert identity(bundle/manifest['archive'])=={k:manifest[k] for k in ('bytes','sha256')}
    links={r['original']:bundle/r['archive'] for r in raw['archives']}
    if links:
        proof=read(bundle/'archive-compaction.json')
        assert len(proof['archives'])==len(raw['archives'])
        for archive, item in zip(raw['archives'],proof['archives']):
            assert identity(bundle/archive['archive'])==item['stored']=={k:archive[k] for k in ('bytes','sha256')}
    files={str(p.relative_to(run)):p for p in run.rglob('*') if p.is_file() or p.is_symlink()}
    assert set(files)==set(manifest['members'])|set(links)
    for name, item in manifest['members'].items():
        assert not files[name].is_symlink() and identity(files[name])==item
    for name, target in links.items(): assert files[name].is_symlink() and files[name].resolve()==target.resolve()
    removed.append(dict(path=str(run.relative_to(ROOT)),bytes=sum(r['bytes'] for r in manifest['members'].values()),basis='all original run members and checked compact archive links'))
    shutil.rmtree(run)
frozen=read(SERIES/'sources.json')
for source in [WORK/name/'archive-check/source' for name in ('normal-30s-01','normal-30s-02')]+[WORK/'frozen-tests/source']:
    files={str(p.relative_to(source)):p for p in source.rglob('*') if p.is_file()}
    assert all('__pycache__' in Path(n).parts and n.endswith('.pyc') for n in set(files)-set(frozen['files']))
    for name, item in frozen['files'].items(): assert identity(files[name])==item
    removed.append(dict(path=str(source.relative_to(ROOT)),bytes=sum(p.stat().st_size for p in files.values()),basis='all frozen source hashes plus generated bytecode'))
    shutil.rmtree(source)
write(SERIES/'storage-closeout.json',dict(status='PASS',removed=removed,
    removed_bytes=sum(r['bytes'] for r in removed),raw_compaction_saved_bytes=compaction['original_bytes']-compaction['stored_bytes'],
    retained='all full raw/run/source/review archives; no previous build removal',
    free_bytes={p:shutil.disk_usage(p).free for p in ('/tmp','/d')}))
print('Checked review archives retained and extracted duplicates removed.')
